def run(cap: bool = True) -> dict:
    """질의 전수를 돌려 top1/3/5 를 센다. 규칙을 끈 채로도 돌 수 있게 인자를 둔다."""
    saved = semantic_search.CAP_WEIGHT
    if not cap:
        semantic_search.CAP_WEIGHT = 0.0
    hits = {1: 0, 3: 0, 5: 0}
    rows = []
    try:
        for query, answers in QUERIES:
            result = semantic_search.search(query, limit=5)
            if result.get("mode") != "semantic":
                # 낮은 점수를 조용히 내지 않는다 — 왜 못 쟀는지 밝히고 멈춘다
                raise SystemExit(f"임베딩을 쓰지 못해 벤치를 못 잰다 — "
                                 f"{result.get('degraded_reason') or result.get('reason')}")
            got = [r["code"] for r in result.get("rows") or []]
            rank = next((i + 1 for i, c in enumerate(got) if c in answers), 0)
            for k in (1, 3, 5):
                if rank and rank <= k:
                    hits[k] += 1
            rows.append({
                "query": query, "rank": rank,
                "top": [{"code": r["code"], "name": r["name"],
                         "similarity": r["similarity"], "score": r["score"],
                         "hit": r["code"] in answers} for r in (result.get("rows") or [])[:3]],
            })
    finally:
        semantic_search.CAP_WEIGHT = saved
    n = len(QUERIES)
    return {"n": n, "cap": cap,
            "top1": hits[1] / n, "top3": hits[3] / n, "top5": hits[5] / n,
            "rows": rows}


def main() -> None:
    cap = "--no-cap" not in sys.argv
    out = run(cap=cap)
    if "--json" in sys.argv:
        print(json.dumps(out, ensure_ascii=False, indent=2))
        return
    print(f"\n질의 {out['n']}건 · 규모 가중 {'켬' if cap else '끔'}\n")
    for row in out["rows"]:
        mark = "✓" if row["rank"] == 1 else (f"{row['rank']}위" if row["rank"] else "✗")
        first = row["top"][0] if row["top"] else {}
        print(f"  {mark:>4}  {row['query'][:30]:32} 1위 {first.get('name', '—')[:14]:16}"
              f" sim {first.get('similarity', 0):.3f}")
    print(f"\n  top1 {out['top1']:.0%} · top3 {out['top3']:.0%} · top5 {out['top5']:.0%}")


if __name__ == "__main__":
    main()
